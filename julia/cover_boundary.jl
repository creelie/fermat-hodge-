# cover_boundary.jl -- port of code/cover_boundary.py (the cover of Proposition VI.40).
#
# B_lambda : x^3 + y^3 + 1 + lambda x^3 y^3 = 0 in P^1 x P^1, lambda not in {0,1};
# F = x1^3 y0^3 + x0^3 y1^3 + x0^3 y0^3 + lambda x1^3 y1^3,  x = x1/x0, y = y1/y0.
# (A) B_lambda is smooth for every lambda not in {0, 1};
# (B) div(y^3 + 1/lambda) = 3 F_x - 3 F_y, so eta = O(1,-1)|_B has 3 eta = 0;
# (C) eta != 0: the three points of F_y have distinct x-values;
# (D) the nine products x^i y^j (0 <= i, j <= 2) restrict to a basis of H^0(B, O(2,2)).
#
# Exact arithmetic over Q with polynomials stored as dictionaries of monomials.
# Two steps of the Python are replaced by exact equivalents:
#  (A) the Python calls sympy.solve on {G = dG = 0} in each of the four affine
#      charts and checks that every solution has lambda in {0, 1}.  Here, in
#      each chart, a Groebner basis (Buchberger, graded reverse lexicographic
#      order, coefficients in Q) of the ideal
#          (G, dG/du, dG/dv, s lambda (lambda - 1) - 1)  in Q[u, v, lambda, s]
#      is computed and found to be {1}.  By the Nullstellensatz the system
#      G = dG/du = dG/dv = 0 then has no solution with lambda (lambda - 1) != 0
#      over an algebraically closed field of characteristic 0, which is the
#      smoothness statement.  As a control the same computation at lambda = 0
#      and lambda = 1 gives proper ideals (the curve is singular there).
#  (D) the Python evaluates the nine monomials numerically (50 digits) at the
#      nine points (x, y) of B_2 over three rational values of x and takes
#      the rank of the 9 x 9 matrix M.  Here the same nine points are used
#      (the three x-values drawn by the Python with its seed, the three roots
#      y of y^3 = r(x) = -(x^3+1)/(1+2x^3) for each), and the matrix
#      N = M^T M is computed exactly: its entries are
#      sum_x x^(i+i') p_(j+j')(x), with p_m the m-th power sum of the three
#      roots (3 r^(m/3) if 3 | m, else 0).  det N = (det M)^2 != 0, so M has rank 9.
# Run: julia --startup-file=no cover_boundary.jl
include(joinpath(@__DIR__, "quadratic_forms.jl"))
using .QuadraticForms: Checks, check, finish

const Q = Rational{BigInt}
const Mono = NTuple{4,Int}
const Poly = Dict{Mono,Q}

mono(e...) = Poly(Mono(e) => Q(1))
cst(c) = c == 0 ? Poly() : Poly((0, 0, 0, 0) => Q(c))
function add(x::Poly, y::Poly, s = Q(1))
    r = copy(x)
    for (k, c) in y
        v = get(r, k, Q(0)) + s * c
        v == 0 ? delete!(r, k) : (r[k] = v)
    end
    return r
end
function mul(x::Poly, y::Poly)
    r = Poly()
    for (k1, c1) in x, (k2, c2) in y
        k = k1 .+ k2; v = get(r, k, Q(0)) + c1 * c2
        v == 0 ? delete!(r, k) : (r[k] = v)
    end
    return r
end
pw(x::Poly, n::Int) = n == 0 ? cst(1) : mul(x, pw(x, n - 1))
function deriv(x::Poly, i::Int)
    r = Poly()
    for (k, c) in x
        k[i] == 0 && continue
        r[ntuple(j -> j == i ? k[j] - 1 : k[j], 4)] = c * k[i]
    end
    return r
end
"substitute variable i by the constant c"
function subsc(x::Poly, i::Int, c)
    r = Poly()
    for (k, v) in x
        k0 = ntuple(j -> j == i ? 0 : k[j], 4)
        w = get(r, k0, Q(0)) + v * Q(c)^k[i]
        w == 0 ? delete!(r, k0) : (r[k0] = w)
    end
    return r
end

# ---- Groebner bases (Buchberger), graded reverse lexicographic order ---------------
grevlex_lt(a::Mono, b::Mono) = begin
    sa, sb = sum(a), sum(b)
    sa != sb && return sa < sb
    for i in 4:-1:1
        a[i] != b[i] && return a[i] > b[i]
    end
    return false
end
function lead(x::Poly)
    best = first(keys(x))
    for k in keys(x); grevlex_lt(best, k) && (best = k); end
    return best
end
divides(a::Mono, b::Mono) = all(a .<= b)
function normal_form(f::Poly, G::Vector{Poly}, LM::Vector{Mono})
    f = copy(f); r = Poly()
    while !isempty(f)
        m = lead(f); c = f[m]; reduced = false
        for (g, lm) in zip(G, LM)
            if divides(lm, m)
                q = Poly(m .- lm => c / g[lm])
                f = add(f, mul(q, g), Q(-1)); reduced = true; break
            end
        end
        if !reduced
            r[m] = c; delete!(f, m)
        end
    end
    return r
end
function spoly(f::Poly, g::Poly, lf::Mono, lg::Mono)
    l = max.(lf, lg)
    return add(mul(Poly(l .- lf => 1 / f[lf]), f), mul(Poly(l .- lg => 1 / g[lg]), g), Q(-1))
end
"Groebner basis of the ideal generated by gens; stops as soon as a nonzero constant is found."
function groebner(gens::Vector{Poly})
    G = Poly[]; LM = Mono[]; pairs = Tuple{Int,Int}[]
    function push_gen!(h)
        lm = lead(h); c = h[lm]
        push!(G, Poly(k => v / c for (k, v) in h)); push!(LM, lm)
        for i in 1:length(G)-1; push!(pairs, (i, length(G))); end
        return lm == (0, 0, 0, 0)
    end
    for f in gens
        h = normal_form(f, G, LM)
        isempty(h) && continue
        push_gen!(h) && return [cst(1)]
    end
    while !isempty(pairs)
        # smallest lcm first
        best = argmin([sum(max.(LM[i], LM[j])) for (i, j) in pairs])
        (i, j) = pairs[best]; deleteat!(pairs, best)
        all(min.(LM[i], LM[j]) .== 0) && continue        # coprime leading monomials: S-polynomial reduces to 0
        h = normal_form(spoly(G[i], G[j], LM[i], LM[j]), G, LM)
        isempty(h) && continue
        push_gen!(h) && return [cst(1)]
    end
    return G
end
is_unit_ideal(G) = length(G) == 1 && G[1] == cst(1)

function det_exact(M::Matrix{Q})
    A = copy(M); n = size(A, 1); d = Q(1)
    for i in 1:n
        p = findfirst(r -> A[r, i] != 0, i:n)
        p === nothing && return Q(0)
        p += i - 1
        if p != i; A[[i, p], :] = A[[p, i], :]; d = -d; end
        d *= A[i, i]
        for r in i+1:n
            A[r, i] == 0 && continue
            A[r, :] -= (A[r, i] / A[i, i]) * A[i, :]
        end
    end
    return d
end

function main()
    C = Checks("cover_boundary.jl")
    # variables of the bihomogeneous equation: (x0, x1, y0, y1), lambda a parameter.
    # In a chart two of them are set to 1; the remaining two are u, v and the
    # polynomial ring is Q[u, v, lambda, s] (positions 1, 2, 3, 4).
    u, v, lam, s = mono(1, 0, 0, 0), mono(0, 1, 0, 0), mono(0, 0, 1, 0), mono(0, 0, 0, 1)
    one = cst(1)
    # F(x0, x1, y0, y1) with the four arguments polynomials
    Fpoly(x0, x1, y0, y1) = add(add(add(mul(pw(x1, 3), pw(y0, 3)), mul(pw(x0, 3), pw(y1, 3))), mul(pw(x0, 3), pw(y0, 3))),
                                mul(lam, mul(pw(x1, 3), pw(y1, 3))))
    charts = ["x0 = y0 = 1" => Fpoly(one, u, one, v), "x0 = y1 = 1" => Fpoly(one, u, v, one),
              "x1 = y0 = 1" => Fpoly(u, one, one, v), "x1 = y1 = 1" => Fpoly(u, one, v, one)]
    rab = add(mul(s, mul(lam, add(lam, one, Q(-1)))), one, Q(-1))      # s lambda (lambda - 1) - 1
    sing0 = String[]; sing1 = String[]
    for (name, G) in charts
        gens = [G, deriv(G, 1), deriv(G, 2)]
        gb = groebner(vcat(gens, [rab]))
        check(C, "(A) chart $name: the ideal (G, dG, s lambda (lambda - 1) - 1) is the unit ideal: no singular point with lambda not in {0, 1}",
              is_unit_ideal(gb))
        is_unit_ideal(groebner([subsc(g, 3, 0) for g in gens])) || push!(sing0, name)
        is_unit_ideal(groebner([subsc(g, 3, 1) for g in gens])) || push!(sing1, name)
    end
    println("    singular points at lambda = 0 in the charts: ", sing0, "; at lambda = 1: ", sing1)
    check(C, "(A) control: B_0 and B_1 are singular (the Groebner basis is not {1} in some chart)", !isempty(sing0) && !isempty(sing1))
    println("(A) B_lambda is smooth for every lambda not in {0, 1}")

    # (B) the fibre of the y-projection over a cube root c of -1/lambda is 3 (oo, c).
    # Ring Q[x0, x1, c, lambda]; multiply by lambda and reduce c^3 -> -1/lambda, i.e. lambda c^3 -> -1.
    x0, x1, c = mono(1, 0, 0, 0), mono(0, 1, 0, 0), mono(0, 0, 1, 0); lam4 = mono(0, 0, 0, 1)
    Gy = add(add(add(pw(x1, 3), mul(pw(x0, 3), pw(c, 3))), pw(x0, 3)), mul(lam4, mul(pw(x1, 3), pw(c, 3))))   # F(x0, x1, 1, c)
    lamGy = Poly()                                    # lambda * Gy with lambda c^3 replaced by -1
    for (k, val) in mul(lam4, Gy)
        @assert k[3] in (0, 3)
        k2, val2 = k[3] == 3 ? ((k[1], k[2], 0, k[4] - 1), -val) : (k, val)
        w = get(lamGy, k2, Q(0)) + val2
        w == 0 ? delete!(lamGy, k2) : (lamGy[k2] = w)
    end
    check(C, "(B) on y^3 = -1/lambda: lambda F(x0, x1, 1, y) = (lambda - 1) x0^3, so the fibre over y = c is 3 (oo, c)",
          lamGy == mul(add(lam4, cst(1), Q(-1)), pw(x0, 3)))
    # the fibre over y = oo: x0^3 + lambda x1^3 = 0; discriminant of t^3 + p t + q is -4 p^3 - 27 q^2
    disc3(p, q) = add(mul(cst(-4), pw(p, 3)), mul(cst(-27), pw(q, 2)))
    check(C, "(B) the fibre over y = oo, x0^3 + lambda = 0, has discriminant -27 lambda^2 != 0: three distinct points",
          disc3(Poly(), lam4) == mul(cst(-27), pw(lam4, 2)))
    println("(B) div(y^3 + 1/lambda) = 3 F_x - 3 F_y, so 3 eta = 0 for eta = O(1,-1)|_B")

    # (C) F_y = {(x, oo): x^3 = -1/lambda}: lambda x^3 + 1 has discriminant -27 lambda^4 (that of
    # a t^3 + d is -27 a^2 d^2), so x^3 + 1/lambda has discriminant -27/lambda^2 != 0.
    check(C, "(C) x^3 + 1/lambda has discriminant -27/lambda^2 != 0: three distinct x-values, no a + b x vanishes on F_y",
          mul(pw(lam4, 2), disc3(Poly(), lam4)) == mul(cst(-27), pw(lam4, 4)))
    println("(C) eta != 0 (a pencil of degree 3 cannot have three distinct base x-values)")

    # (D) lambda = 2; the nine points over x = -12/5, -16/3, -13/4 (the values drawn by the Python).
    xs = Q[-12 // 5, -16 // 3, -13 // 4]
    rs = [-(x^3 + 1) / (1 + 2x^3) for x in xs]        # y^3 = r(x)
    check(C, "(D) the nine points (x, y), y^3 = r(x), lie on B_2 and are distinct (r(x) != 0, x distinct)",
          all(x^3 + r + 1 + 2 * x^3 * r == 0 && r != 0 for (x, r) in zip(xs, rs)) && length(Set(xs)) == 3)
    psum(m, r) = m % 3 == 0 ? 3 * r^div(m, 3) : Q(0)  # power sums of the roots of t^3 - r
    idx = [(i, j) for i in 0:2 for j in 0:2]
    N = Q[sum(x^(i + i2) * psum(j + j2, r) for (x, r) in zip(xs, rs)) for (i, j) in idx, (i2, j2) in idx]
    d = det_exact(N)
    check(C, "(D) det(M^T M) != 0 for the evaluation matrix M of the nine monomials x^i y^j at the nine points: rank 9", d != 0)
    println("    det(M^T M) = ", numerator(d), "/", denominator(d))
    println("(D) the multiplication map H^0(K+eta) x H^0(K-eta) -> H^0(2K) is onto (rank 9)")
    finish(C)
end
main()
